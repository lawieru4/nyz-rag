import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import test from "node:test";
import pg from "pg";
import { closeDatabase, getPool, migrate, withTransaction } from "../src/db.js";
import { approveChatReview, createChatMessage, createSource, exportChatReview, getChatReview, listChatMessages, listSessionMessages, rateChatMessage, saveChatReview, upsertDocument } from "../src/repository.js";
import { emptyChatReview } from "../src/chat-review.js";
import { ARTICLE_LIST_URL, articleDocument } from "./article-fixtures.js";
import type { ChatReviewInput } from "@nyz-rag/types";

test("feedback ownership, filters, review CAS approval invalidation and evidence-checked allowlist export", { skip: process.env.NYZ_INTEGRATION_TEST !== "1", timeout: 60000 }, async () => {
  const previous = process.env.DATABASE_URL;
  const connectionString = previous ?? "postgresql://nyzrag:nyzrag@localhost:5432/nyzrag";
  const admin = new pg.Pool({ connectionString });
  const schema = `nyz_feedback_test_${randomBytes(6).toString("hex")}`;
  await admin.query(`CREATE SCHEMA ${schema}`);
  const url = new URL(connectionString);
  url.searchParams.set("options", `-c search_path=${schema},public`);
  process.env.DATABASE_URL = url.toString();
  const owner = { visitorHash: "owner-private" };
  try {
    await migrate();
    await createChatMessage({ id: "message", question: "RAW_PRIVATE_QUESTION", answer: "RAW_PRIVATE_ANSWER", sources: [], owner });
    await createChatMessage({ id: "other", question: "Other", answer: "Other", sources: [], owner: { visitorHash: "someone-else" } });
    assert.equal(await rateChatMessage("message", "negative", { visitorHash: "someone-else" }, undefined, ["outdated"]), false);
    assert.equal(await rateChatMessage("message", "negative", owner, undefined, ["missing-evidence", "outdated"]), true);
    assert.equal((await listChatMessages({ rating: "negative", page: 1, pageSize: 10 })).total, 1);
    assert.equal((await listChatMessages({ rating: "positive", page: 1, pageSize: 10 })).total, 0);
    assert.deepEqual((await listChatMessages({ rating: "negative", page: 1, pageSize: 10 })).logs[0].feedbackReasons, ["missing-evidence", "outdated"]);
    await rateChatMessage("message", "positive", owner);
    assert.equal((await listChatMessages({ rating: "positive", page: 1, pageSize: 10 })).total, 1);
    await rateChatMessage("message", null, owner, undefined, ["outdated"]);
    const logs = await listChatMessages({ rating: "unrated", status: "new", page: 1, pageSize: 10 });
    assert.equal(logs.total, 2);
    assert.deepEqual(logs.logs.find((log) => log.id === "message")!.feedbackReasons, []);
    assert.equal("review" in logs.logs[0], false);
    assert.equal("visitorHash" in logs.logs[0], false);
    assert.deepEqual(await getChatReview("message"), emptyChatReview());
    assert.equal(await getChatReview("missing"), null);
    const source = await createSource({ name: "Test", url: ARTICLE_LIST_URL, kind: "文章 API", frequency: "" });
    const documentId = await withTransaction((tx) => upsertDocument(tx, articleDocument(source.id, "123", "Public title", "Public evidence excerpt.")));
    await getPool().query("UPDATE documents SET status = 'ready' WHERE id = $1", [documentId]);
    const review: ChatReviewInput = { status: "investigating", reasons: ["incorrect-answer"], notes: "PRIVATE_NOTES", correctedAnswer: "PRIVATE_CORRECTION", candidate: { question: "Public question", answer: "Public correction", history: [], filters: null, type: "fact", split: "dev", answerable: true, labels: [{ articleKey: "123", relevance: 2, evidence: ["Public evidence excerpt."] }] } };
    assert.equal(await saveChatReview("message", 0, review), true);
    assert.equal(await saveChatReview("message", 0, review), false);
    assert.equal((await listChatMessages({ status: "investigating", page: 1, pageSize: 10 })).total, 1);
    await assert.rejects(exportChatReview("message", 1), /approval/);
    assert.equal(await approveChatReview("message", 0, "admin"), false);
    assert.equal(await approveChatReview("message", 1, "admin"), true);
    const dataset = (await exportChatReview("message", 1))!;
    assert.equal(dataset.schemaVersion, 2);
    assert.doesNotMatch(JSON.stringify(dataset), /RAW_PRIVATE|PRIVATE_NOTES|PRIVATE_CORRECTION|owner-private|message|visitorHash/);
    assert.equal((await getPool().query("SELECT approved_by FROM chat_messages WHERE id = 'message'")).rows[0].approved_by, "admin");
    const writes = await Promise.all([saveChatReview("message", 1, { ...review, notes: "Edit A" }), saveChatReview("message", 1, { ...review, notes: "Edit B" })]);
    assert.equal(writes.filter(Boolean).length, 1);
    assert.equal((await getChatReview("message"))!.approvedRevision, null);
    await assert.rejects(exportChatReview("message", 2), /approval/);
    assert.equal(await approveChatReview("message", 2, "admin"), true);
    await getPool().query("UPDATE documents SET content = 'Changed article' WHERE id = $1", [documentId]);
    await assert.rejects(exportChatReview("message", 2), /exact excerpt/);
    await assert.rejects(approveChatReview("message", 2, "admin"), /exact excerpt/);
    await getPool().query("UPDATE documents SET content = 'Public evidence excerpt.' WHERE id = $1", [documentId]);
    const followup = { ...review, candidate: { ...review.candidate!, type: "followup" as const, history: [{ question: "Public prior question", answer: "Public prior answer" }], filters: { categories: ["Public category"], publishedFrom: "2026-01-01" } } };
    assert.equal(await saveChatReview("message", 2, followup), true);
    assert.equal(await approveChatReview("message", 3, "admin"), true);
    const annotated = (await exportChatReview("message", 3))!;
    assert.deepEqual(annotated.questions[0].history, followup.candidate.history);
    assert.deepEqual(annotated.questions[0].filters, followup.candidate.filters);
    await getPool().query("UPDATE documents SET status = 'failed' WHERE id = $1", [documentId]);
    await assert.rejects(exportChatReview("message", 3), /missing or ambiguous/);
    assert.equal(await saveChatReview("message", 3, { ...review, candidate: null }), true);
    assert.equal(await approveChatReview("message", 4, "admin"), false);
    assert.equal(await saveChatReview("message", 4, { ...review, candidate: { ...review.candidate!, type: "unanswerable", answerable: false, labels: [] } }), true);
    assert.equal(await approveChatReview("message", 5, "admin"), true);
    assert.equal((await exportChatReview("message", 5))!.questions[0].answerable, false);
    assert.deepEqual(await listSessionMessages("none"), []);
  } finally {
    await closeDatabase();
    if (previous === undefined) delete process.env.DATABASE_URL; else process.env.DATABASE_URL = previous;
    await admin.query(`DROP SCHEMA ${schema} CASCADE`);
    await admin.end();
  }
});
